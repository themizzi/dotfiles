-- Move windows between monitors
-- Resolve a real output at keypress time; at the desktop edge, do nothing.
local function move_window_to_monitor(direction)
    return function()
        local window = hl.get_active_window()
        if not window or not window.monitor then
            return
        end
        local current = window.monitor
        local target, nearest
        for _, monitor in ipairs(hl.get_monitors()) do
            local dx = monitor.position.x - current.position.x
            local dy = monitor.position.y - current.position.y
            if monitor.id ~= current.id and not monitor.is_mirror and dx * direction > 0 then
                local distance = dx * dx + dy * dy
                if not nearest or distance < nearest then
                    target, nearest = monitor, distance
                end
            end
        end
        if target then
            hl.dispatch(hl.dsp.window.move({ monitor = target.name }))
        end
    end
end

hl.bind(
    mod .. " + SHIFT + left",
    move_window_to_monitor(-1)
)
hl.bind(
    mod .. " + SHIFT + right",
    move_window_to_monitor(1)
)

